/** النوايا العربية-الإنجليزية الثلاث التي يطلبها المحرر ← نية موجّه النماذج. */
export const BOT_IMAGE_INTENTS = ["realistic", "illustration", "explanatory"] as const;
export type BotImageIntent = (typeof BOT_IMAGE_INTENTS)[number];
const INTENT_TO_TASK = { realistic: "photo", illustration: "opinion_art", explanatory: "infographic" } as const;
/** قائمة بيضاء: نفس نماذج مسار المحرر البشري (nanoBananaService.GOOGLE_MODEL_MAP). */
export const BOT_IMAGE_MODELS = [DEFAULT_IMAGE_MODEL, LEGACY_IMAGE_MODEL, "recraft-v3", "flux-1.1-pro", "ideogram-2"] as const;

const aspectRatio = z.enum(["1:1", "16:9", "4:3", "9:16", "21:9", "3:4"]);
const imageInput = z.object({
  prompt: z.string().trim().min(3).max(2000),
  style: z.string().trim().min(1).max(200).optional(),
  aspectRatio: aspectRatio.optional(),
  intent: z.enum(BOT_IMAGE_INTENTS).optional(),
  model: z.enum(BOT_IMAGE_MODELS).optional(),
  styleSlug: z.string().trim().min(1).max(50).regex(/^[a-z0-9-]+$/).optional(),
}).strict();
const searchInput = z.object({
  q: z.string().trim().min(1).max(200),
  limit: z.coerce.number().int().min(1).max(50).default(20),
}).strict();

function parse<T>(schema: z.ZodType<T>, input: unknown): T {
  const result = schema.safeParse(input);
  if (!result.success) throw new BotDraftError(400, "validation_error", "بيانات الطلب غير صالحة", { issues: result.error.issues });
  return result.data;
}

/** Persist generated bytes to storage + media library; never return a placeholder or provider data URI. */
async function persistGeneratedImage(input: { imageData: string; prompt: string; model: string; userId: string }) {
  const { newsImageStorageService } = await import("./newsImageStorageService");
  const uploaded = await newsImageStorageService.upload({
    buffer: Buffer.from(input.imageData, "base64"),
    filename: `bot-${randomUUID()}.png`, mimeType: "image/png",
    purpose: "article-ai-generated", metadata: { source: "bot-editor" },
  });
  const deliveryUrl = uploaded.deliveryUrl;
  if (!uploaded.success || !deliveryUrl?.startsWith("https://") || !isSafeImageUrl(deliveryUrl)) {
    throw new BotDraftError(502, "generation_failed", "تعذر حفظ الصورة في التخزين الآمن");
  }
  const safeThumbnail = uploaded.thumbnailUrl;
  const { saveGeneratedImage } = await import("./mediaGenerationService");
  const media = await saveGeneratedImage({
    imageUrl: deliveryUrl,
    thumbnailUrl: safeThumbnail && isSafeImageUrl(safeThumbnail) ? safeThumbnail : null,
    prompt: input.prompt, model: input.model, userId: input.userId,
  });
  return { media, deliveryUrl };
}

/** Generate and persist a real image. intent/model/styleSlug mirror the human nano-banana route. */
export async function generateBotImage(_lang: BotEditorLanguage, body: unknown) {
  const input = parse(imageInput, body);
  const userId = await resolveBotAuthorId();
  const { recordBotEditorOperation } = await import("./botEditorOperationsAudit");
  const meta = { language: _lang, intent: input.intent ?? null, model: input.model ?? null, styleSlug: input.styleSlug ?? null };
  await recordBotEditorOperation({ actorId: userId, operation: "generate_image", outcome: "started", metadata: meta });
  try {
    const { generateWithSmartRouter } = await import("./imageModelRouter");
    let request: Parameters<typeof generateWithSmartRouter>[0] = {
      prompt: input.style ? `${input.prompt}\nVisual style: ${input.style}` : input.prompt,
      aspectRatio: input.aspectRatio ?? "16:9",
      numImages: 1,
      ...(input.intent ? { intent: INTENT_TO_TASK[input.intent] } : {}),
      ...(input.model ? { model: input.model } : {}),
    };
    if (input.styleSlug) {
      const { resolveGenerationStyle } = await import("./imageStyleService");
      const { composeImagePrompt } = await import("@shared/imageStyles");
      const { style, variant, model } = await resolveGenerationStyle(input.styleSlug, null, input.model ?? null);
      if (style.slug !== input.styleSlug) throw new BotDraftError(422, "validation_error", "styleSlug غير موجود أو غير مفعّل", { styleSlug: input.styleSlug });
      const composed = composeImagePrompt({ style, variant, content: input.prompt });
      request = { ...request, prompt: composed.prompt, negativePrompt: composed.negativePrompt, model, styleSlug: style.slug };
    }
    const generated = await generateWithSmartRouter(request);
    if (!generated.success || !generated.imageData) {
      throw new BotDraftError(502, "generation_failed", "تعذر توليد الصورة");
    }
    const { media, deliveryUrl } = await persistGeneratedImage({ imageData: generated.imageData, prompt: input.prompt, model: generated.modelUsed, userId });
    await recordBotEditorOperation({ actorId: userId, operation: "generate_image", outcome: "succeeded", metadata: { ...meta, assetId: media.id, modelUsed: generated.modelUsed, detectedIntent: generated.detectedIntent } });
    return { media, deliveryUrl, isAiGenerated: true, model: generated.modelUsed, intent: generated.detectedIntent };
  } catch (error) {
    await recordBotEditorOperation({ actorId: userId, operation: "generate_image", outcome: "failed", metadata: meta });
    throw error;
  }
}

const editInput = z.object({
  sourceImageUrl: z.string().trim().url().max(2000),
  prompt: z.string().trim().min(3).max(2000),
  aspectRatio: aspectRatio.optional(),
}).strict();
const EDIT_SOURCE_MAX_BYTES = 10 * 1024 * 1024;

/** مصادر التعديل: صور سبق فقط (R2/media.sabq.org أو Cloudflare Images)، لا روابط خارجية (SSRF). */
export function isEditableSourceImageUrl(raw: string): boolean {
  if (!isSafeImageUrl(raw)) return false;
  try {
    const { hostname } = new URL(raw);
    if (hostname === "imagedelivery.net" || hostname.endsWith(".imagedelivery.net")) return true;
  } catch { return false; }
  return isNewsImageR2DeliveryUrl(raw);
}

/** تحرير صورة موجودة (صورة مرجعية + تعليمات) ثم حفظ النتيجة في المكتبة. لا يغيّر أي خبر. */
export async function editBotImage(_lang: BotEditorLanguage, body: unknown) {
  const input = parse(editInput, body);
  if (!input.sourceImageUrl.startsWith("https://") || !isEditableSourceImageUrl(input.sourceImageUrl)) {
    throw new BotDraftError(422, "validation_error", "مصدر الصورة يجب أن يكون صورة مرفوعة على سبق (media.sabq.org أو Cloudflare Images)");
  }
  const userId = await resolveBotAuthorId();
  const { recordBotEditorOperation } = await import("./botEditorOperationsAudit");
  const meta = { language: _lang };
  await recordBotEditorOperation({ actorId: userId, operation: "edit_image", outcome: "started", metadata: meta });
  try {
    let response: Response;
    try { response = await fetch(input.sourceImageUrl, { redirect: "error", signal: AbortSignal.timeout(15_000) }); }
    catch { throw new BotDraftError(422, "validation_error", "تعذر جلب الصورة المصدر"); }
    const mime = response.headers.get("content-type")?.split(";")[0]?.trim().toLowerCase() ?? "";
    if (!response.ok || !["image/png", "image/jpeg", "image/webp"].includes(mime)) throw new BotDraftError(422, "invalid_image", "الصورة المصدر غير صالحة (png/jpeg/webp)");
    const buffer = Buffer.from(await response.arrayBuffer());
    if (buffer.length > EDIT_SOURCE_MAX_BYTES) throw new BotDraftError(422, "file_too_large", "الصورة المصدر أكبر من 10MB");
    const { verifyImageMagicBytes } = await import("../utils/imageVerify");
    if (!(await verifyImageMagicBytes(buffer, mime)).ok) throw new BotDraftError(422, "invalid_image", "الصورة المصدر ليست ملف صورة صالحاً");
    const { generateImage } = await import("./nanoBananaService");
    const generated = await generateImage({
      prompt: `Edit the attached image according to this instruction and keep every other element unchanged: ${input.prompt}`,
      aspectRatio: input.aspectRatio, model: DEFAULT_IMAGE_MODEL, numImages: 1,
      referenceImages: [`data:${mime};base64,${buffer.toString("base64")}`],
    });
    if (!generated.success || !generated.imageData) throw new BotDraftError(502, "generation_failed", "تعذر تعديل الصورة");
    const model = String(generated.metadata?.model ?? DEFAULT_IMAGE_MODEL);
    const { media, deliveryUrl } = await persistGeneratedImage({ imageData: generated.imageData, prompt: input.prompt, model, userId });
    await recordBotEditorOperation({ actorId: userId, operation: "edit_image", outcome: "succeeded", metadata: { ...meta, assetId: media.id, modelUsed: model } });
    return { media, deliveryUrl, isAiGenerated: true, model };
  } catch (error) {
    await recordBotEditorOperation({ actorId: userId, operation: "edit_image", outcome: "failed", metadata: meta });
    throw error;
  }
}

const deleteMediaInput = z.object({ updateReason: z.string().trim().min(3).max(500) }).strict();

/**
 * حذف من مكتبة الوسائط لما ولّده/رفعه البوت نفسه فقط، وغير المستخدم في أي مادة.
 * الملف الفعلي (blob) يبقى في التخزين، وسجل التدقيق يحمل لقطة الصف للاستعادة.
 */
export async function deleteBotMedia(mediaId: string, body: unknown) {
  const input = parse(deleteMediaInput, body ?? {});
  if (!/^[A-Za-z0-9_-]{1,128}$/.test(mediaId)) throw new BotDraftError(400, "validation_error", "معرّف الملف غير صالح");
  const userId = await resolveBotAuthorId();
  const { articleMediaAssets, mediaUsageLog } = await import("@shared/schema");
  const { recordBotEditorOperation } = await import("./botEditorOperationsAudit");
  const result = await db.transaction(async (tx) => {
    const [row] = await tx.select().from(mediaFiles).where(eq(mediaFiles.id, mediaId)).limit(1).for("update");
    if (!row) throw new BotDraftError(404, "not_found", "ملف الوسائط غير موجود");
    if (row.uploadedBy !== userId) throw new BotDraftError(403, "forbidden_action", "يحذف البوت ما رفعه أو ولّده بنفسه فقط");
    const [asset] = await tx.select({ articleId: articleMediaAssets.articleId }).from(articleMediaAssets).where(eq(articleMediaAssets.mediaFileId, mediaId)).limit(1);
    const [usage] = await tx.select({ id: mediaUsageLog.id }).from(mediaUsageLog).where(eq(mediaUsageLog.mediaId, mediaId)).limit(1);
    const legacyUsed = Array.isArray(row.usedIn) && row.usedIn.length > 0;
    if (asset || usage || legacyUsed) {
      throw new BotDraftError(409, "not_a_draft", "الملف مستخدم في مادة أو محتوى آخر ولا يُحذف", { articleId: asset?.articleId ?? null });
    }
    await tx.delete(mediaFiles).where(eq(mediaFiles.id, mediaId));
    return row;
  });
  await recordBotEditorOperation({
    actorId: userId, operation: "delete_media", outcome: "succeeded",
    metadata: { mediaId, url: result.url.slice(0, 500), fileName: result.fileName, mimeType: result.mimeType, isAiGenerated: result.isAiGenerated, blobRetained: true, reason: input.updateReason },
  });
  return { deleted: true, mediaId, blobRetained: true };
}

/** Ranked lexical library search; expose rights information to the editor. */
export async function searchBotMedia(_lang: BotEditorLanguage, query: unknown) {
  const input = parse(searchInput, query);
  const search = buildMediaSearch(input.q);
  if (!search) return { files: [], total: 0 };
  const files = await db.select({
    id: mediaFiles.id, url: mediaFiles.url, thumbnailUrl: mediaFiles.thumbnailUrl,
    title: mediaFiles.title, altText: mediaFiles.altText, caption: mediaFiles.caption,
    isAiGenerated: mediaFiles.isAiGenerated, licenseType: mediaFiles.licenseType,
    rightsVerified: mediaFiles.rightsVerified, rightsNote: mediaFiles.rightsNote,
    creditText: mediaFiles.creditText, copyrightHolder: mediaFiles.copyrightHolder,
  }).from(mediaFiles).where(and(eq(mediaFiles.type, "image"), search.where))
    .orderBy(desc(search.score), desc(mediaFiles.createdAt), desc(mediaFiles.id)).limit(input.limit);
  // Bound response size even if old library metadata contains unusually long values.
  const bounded = files.map((file) => ({ ...file,
    title: file.title?.slice(0, 300), altText: file.altText?.slice(0, 300),
    caption: file.caption?.slice(0, 1000), rightsNote: file.rightsNote?.slice(0, 1000),
    creditText: file.creditText?.slice(0, 300), copyrightHolder: file.copyrightHolder?.slice(0, 300),
    licenseType: file.licenseType?.slice(0, 100), url: file.url.slice(0, 2000),
    thumbnailUrl: file.thumbnailUrl?.slice(0, 2000),
  }));
  return { files: bounded, total: bounded.length };
}

const coverInput = z.object({ style: imageInput.shape.style, aspectRatio: imageInput.shape.aspectRatio, intent: imageInput.shape.intent, model: imageInput.shape.model, styleSlug: imageInput.shape.styleSlug }).strict();
export async function generateBotCover(lang: BotEditorLanguage, id: string, body: unknown) {
  const input = parse(coverInput, body);
  const { assertBotEditorEditable } = await import("./botEditorWrites");
  await assertBotEditorEditable(lang, id);
  const { readBotArticle } = await import("./botEditorReads");
  const article = await readBotArticle(lang, id, { includeContent: "1" });
  const expectedUpdatedAt = new Date(article.updatedAt);
  if (!Number.isFinite(expectedUpdatedAt.getTime())) throw new BotDraftError(409, "draft_changed", "تعذر التحقق من نسخة الخبر");
  const result = await generateBotImage(lang, { prompt: article.title, ...input });
  const { editBotArticle } = await import("./botEditorWrites");
  const draft = await editBotArticle(lang, id, { imageUrl: result.deliveryUrl, isAiGeneratedImage: true }, { expectedUpdatedAt });
  return { draft, ...result };
}

const extraNames = ["summary", "keywords", "seo", "subtitle", "excerpt", "alternativeTitle", "seoTitle", "seoDescription"] as const;
const extrasInput = z.object({ fields: z.array(z.enum(extraNames)).min(1).max(extraNames.length).optional() }).strict();
export async function regenerateEditorExtras(lang: BotEditorLanguage, id: string, body: unknown) {
  const input = parse(extrasInput, body);
  const fields = Array.from(new Set(input.fields ?? ["summary", "keywords", "seo"]));
  const { assertBotEditorEditable } = await import("./botEditorWrites");
  await assertBotEditorEditable(lang, id);
  const { readBotArticle } = await import("./botEditorReads");
  const article = await readBotArticle(lang, id, { includeContent: "1" });
  const content = article.content ?? "";
  if (content.replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/\s+/g, " ").trim().length < 100)
    throw new BotDraftError(422, "content_too_short", "المتن أقصر من 100 حرف — لا يكفي لتوليد الملحقات", { minChars: 100 });
  const expectedUpdatedAt = new Date(article.updatedAt);
  if (!Number.isFinite(expectedUpdatedAt.getTime())) throw new BotDraftError(409, "draft_changed", "تعذر التحقق من نسخة الخبر");
  const { generateSmartContent, withRetry } = await import("../openai");
  let generated: Awaited<ReturnType<typeof generateSmartContent>>;
  try { generated = await withRetry(() => generateSmartContent(content, lang), 3, "SmartContent"); }
  catch { throw new BotDraftError(502, "generation_failed", "تعذر توليد الملحقات"); }
  const { buildRegeneratedExtrasInput } = await import("./botDraftsService");
  const mapped = buildRegeneratedExtrasInput(
    [...(fields.includes("summary") || fields.includes("excerpt") ? ["summary" as const] : []), ...(fields.includes("keywords") ? ["keywords" as const] : []), ...(fields.some(f => ["seo", "seoTitle", "seoDescription"].includes(f)) ? ["seo" as const] : [])],
    { summary: generated.smartSummary, seo: { ...generated.seo, keywords: generated.keywords } },
  );
  if (!fields.includes("seo") && !fields.includes("seoTitle")) delete mapped.seoTitle;
  if (!fields.includes("seo") && !fields.includes("seoDescription")) delete mapped.seoDescription;
  const update: Record<string, unknown> = { ...mapped };
  if (fields.includes("subtitle") && generated.subTitle?.trim()) update.subtitle = generated.subTitle.trim().slice(0, 300);
  // Store the optional alternate headline in the article SEO metadata.
  const alternativeTitle = fields.includes("alternativeTitle") ? generated.mainTitle?.trim().slice(0, 300) : undefined;
  if (alternativeTitle) update.alternativeTitle = alternativeTitle;
  const required = new Set<string>();
  for (const field of fields) {
    if (field === "summary" || field === "excerpt") required.add("excerpt");
    else if (field === "seo") { required.add("seoTitle"); required.add("seoDescription"); }
    else required.add(field);
  }
  if ([...required].some((key) => !(key in update))) {
    throw new BotDraftError(502, "generation_failed", "لم يرجع المولّد جميع القيم المطلوبة — لم يُحفظ شيء", { fields });
  }
  // The English gateway uses an English prompt; reject obviously wrong-language
  // responses instead of persisting them. Arabic names within English are fine.
  if (lang === "en" && Object.values(update).some((value) => {
    const text = Array.isArray(value) ? value.join(" ") : typeof value === "string" ? value : "";
    const letters = text.match(/[A-Za-z\u0600-\u06ff]/g) ?? [];
    const arabic = text.match(/[\u0600-\u06ff]/g) ?? [];
    return letters.length > 0 && arabic.length / letters.length > 0.5;
  })) throw new BotDraftError(502, "generation_failed", "لغة الملحقات المولّدة غير صحيحة — لم يُحفظ شيء");
  const { editBotArticle } = await import("./botEditorWrites");
  const draft = Object.keys(update).length ? await editBotArticle(lang, id, update, { expectedUpdatedAt }) : article;
  return { draft, regenerated: { fields, ...update, ...(alternativeTitle ? { alternativeTitle } : {}) } };
}
