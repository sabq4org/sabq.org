export function servicePageFaq(faq: FaqItem[]): FaqItem[] {
  return faq.map((item) => {
    const rewrite = REWRITES[item.question];
    if (!rewrite) return item;
    const question = rewrite.question ?? item.question;
    if (!rewrite.from) return { ...item, question };
    if (!item.answer.includes(rewrite.from)) return item;
    return { ...item, question, answer: item.answer.replace(rewrite.from, rewrite.to) };
  });
}
