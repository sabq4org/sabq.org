export function getLucideIcon(iconName?: string | null, fallback: LucideIcon = Circle): LucideIcon {
  if (!iconName) return fallback;
  return ICONS[iconName] || ICONS[iconName.charAt(0).toUpperCase() + iconName.slice(1)] || fallback;
}
