#!/usr/bin/env node
// Auto-generates spa-index-html.generated.ts containing the freshly-built
// SPA shell from dist/public/index.html. The Edge Middleware imports this
// and returns it as a direct Response — never going through Vercel's
// rewrite-caching layer, which empirically holds /index.html globally for
// 90+ seconds despite every no-store header we set.
//
// Runs immediately after `vite build` (see package.json build:client) so
// every Vercel deploy bakes the current build's chunk references into the
// middleware bundle.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, "..");
const inputPath = resolve(projectRoot, "dist/public/index.html");
const outputPath = resolve(projectRoot, "spa-index-html.generated.ts");

const html = readFileSync(inputPath, "utf-8");
const buildId = Date.now().toString();

const content = `// AUTO-GENERATED by scripts/embed-spa-html.js. Do not edit by hand.
// Regenerated on every \`npm run build:client\` so the Edge Middleware
// ships with the current build's chunk references baked in.
//
// Bytes: ${html.length}
// Generated at: ${new Date().toISOString()}

export const SPA_INDEX_HTML: string = ${JSON.stringify(html)};
export const SPA_EMBED_BUILD_ID: string = ${JSON.stringify(buildId)};
`;

writeFileSync(outputPath, content);
console.log(
  `[embed-spa-html] wrote ${outputPath} (${html.length} bytes of HTML, buildId=${buildId})`,
);
